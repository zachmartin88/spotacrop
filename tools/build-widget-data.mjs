// Writes ios/App/CropWidget/CropDays.swift: the crop-of-the-day rotation, so the home-screen widget shows
// the same crop as the app (games.js cropOfTheDay) without needing the app to run.
import fs from 'node:fs';
import path from 'node:path';
globalThis.localStorage = { getItem: () => null, setItem: () => {} };
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const { prettyName, NOTES } = await import(path.join(ROOT, 'data.js'));
const { cropEmoji } = await import(path.join(ROOT, 'palette.js'));

// Same as games.js (keep in sync).
function rng(seed) {
  let h = 2166136261;
  for (const ch of String(seed)) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return () => { h = Math.imul(h ^ (h >>> 15), 2246822507); h = Math.imul(h ^ (h >>> 13), 3266489909); return ((h ^= h >>> 16) >>> 0) / 4294967296; };
}
const shuffle = (a, r) => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const games = fs.readFileSync(path.join(ROOT, 'games.js'), 'utf8');
const FEATURED = JSON.parse(/const FEATURED = (\[[^\]]+\])/.exec(games)[1]);
const order = shuffle(FEATURED, rng('fieldsight-crops'));
const q = (s) => JSON.stringify(String(s || '')).replace(/\\u([0-9a-f]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
const rows = order.map((c) => `    Crop(code: ${c}, name: ${q(prettyName(c))}, emoji: ${q(cropEmoji(c))}, note: ${q((NOTES[c] || '').split(/(?<=\.)\s/)[0])}),`);
fs.writeFileSync(path.join(ROOT, 'ios/App/CropWidget/CropDays.swift'), `// Generated by tools/build-widget-data.mjs from games.js. Do not edit by hand.
import Foundation

struct Crop { let code: Int; let name: String; let emoji: String; let note: String }

/// The crop of the day, matching the app: day number (local time) modulo the shuffled list.
enum CropDays {
  static let order: [Crop] = [
${rows.join('\n')}
  ]
  static func crop(on date: Date) -> Crop {
    let offset = TimeInterval(TimeZone.current.secondsFromGMT(for: date))
    let day = Int(floor((date.timeIntervalSince1970 + offset) / 86400))
    return order[((day % order.count) + order.count) % order.count]
  }
}
`);
console.log(`CropDays.swift: ${order.length} crops; today ${prettyName(order[Math.floor((Date.now() - new Date().getTimezoneOffset() * 60000) / 86400000) % order.length])}`);
